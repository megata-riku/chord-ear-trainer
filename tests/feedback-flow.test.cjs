const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../dist/feedback-flow.js'),'utf8'),context);
const flow=vm.runInContext('FeedbackFlow',context),Clock=vm.runInContext('FeedbackClock',context);
assert.equal(flow.normalize().mode,'auto');assert.equal(flow.normalize().showNextButton,false);
assert.equal(flow.normalize({mode:'invalid',delayMs:-1}).delayMs,700);
assert.equal(flow.shouldReview('auto',false),false);
assert.equal(flow.shouldReview('wrongStop',false),true);
assert.equal(flow.shouldReview('wrongStop',true),false);
assert.equal(flow.shouldReview('manual',true),true);
let queued=[],id=0,calls=0;
const clock=new Clock({set:(callback,delay)=>{queued.push({callback,delay,id:++id});return id;},clear:()=>{}});
clock.schedule(()=>calls++,700);assert.equal(queued[0].delay,700);
clock.cancel();queued[0].callback();assert.equal(calls,0,'paused or finished feedback must never advance');
clock.schedule(()=>calls+=100,1200);clock.schedule(()=>calls++,2000);
queued[1].callback();assert.equal(calls,0,'replaced settings invalidate the old timer');
queued[2].callback();assert.equal(calls,1,'only the latest timer advances');
clock.schedule(()=>calls++,700);clock.cancel();queued[3].callback();assert.equal(calls,1,'manual next / session end cancels auto-next');
console.log('PASS: defaults, wrong-answer stopping, manual review, pause/cancel, settings replacement, exactly one active auto-next timer.');
